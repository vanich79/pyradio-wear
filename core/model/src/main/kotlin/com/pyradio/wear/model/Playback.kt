package com.pyradio.wear.model

/**
 * Что сейчас происходит со звуком.
 *
 * Состояние всегда несёт станцию, к которой относится, — кроме [Idle]. Это
 * избавляет экран от вопроса «а к чему относится эта ошибка», когда пользователь
 * успел переключиться, пока предыдущая станция отваливалась.
 */
sealed interface PlaybackState {

    /** Ничего не играет и не пытается. */
    data object Idle : PlaybackState

    /** Идёт разворачивание плейлиста или установка соединения — звука ещё нет. */
    data class Connecting(val station: Station) : PlaybackState

    /** Соединение есть, буфер набирается. Пауза в звуке, но не отказ. */
    data class Buffering(val station: Station) : PlaybackState

    /**
     * Звук идёт. [title] — то, что станция сообщила о текущем треке через ICY.
     *
     * `null` означает «станция метаданных не передаёт», и это не то же самое,
     * что пустая строка: первое показывается именем станции, второе — прочерком.
     */
    data class Playing(val station: Station, val title: String?) : PlaybackState

    /** Станция не заиграла или оборвалась. */
    data class Failed(val station: Station, val reason: FailureReason) : PlaybackState
}

/**
 * Почему станция не играет.
 *
 * Разделение существует ради текста на экране: «нет сети» и «станция молчит» —
 * это разные действия пользователя, и сваливать их в одно «ошибка» значит
 * заставлять его гадать, ждать ему или переключаться.
 */
enum class FailureReason {
    /** У часов нет интернета. Единственная причина, где виноваты не мы и не станция. */
    NO_NETWORK,

    /** Плейлист скачался, но внутри не оказалось ни одного адреса. */
    EMPTY_PLAYLIST,

    /** Все адреса из плейлиста перепробованы, ни один не ответил. */
    STREAM_UNREACHABLE,

    /** Сервер ответил, но отдал не звук — чаще всего HTML-заглушку «станция закрыта». */
    NOT_AUDIO,

    /** Поток есть, но в формате, который плеер не разбирает. */
    UNSUPPORTED_FORMAT,
}
